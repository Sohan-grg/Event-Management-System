    private void jButton8ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton8ActionPerformed
                                         
    String id = jTextField2.getText();
    String name = jTextField3.getText();
    String location = jTextField4.getText();
    String date = jFormattedTextField1.getText().trim();
    String deadline = jFormattedTextField2.getText().trim();

    if (id.isEmpty() || name.isEmpty() || location.isEmpty() || date.isEmpty() || deadline.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill all fields");
        return;
    }

    Event event = new Event(id, name, location, date, deadline);

    if (EventController.addEvent(event)) {
        loadEvents();
        clearFields();
        JOptionPane.showMessageDialog(this, "Event added successfully");
    } else {
        JOptionPane.showMessageDialog(this, "Event ID already exists!");
    }

 if (date.contains("_") || deadline.contains("_")) {
        JOptionPane.showMessageDialog(this,
            "Enter dates in dd-MM-yyyy format");
        return;
    }
  


       
    }//GEN-LAST:event_jButton8ActionPerformed

    
    private void jButton9ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton9ActionPerformed
                                           
        String id = jTextField2.getText();

    if (id.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter Event ID to update");
        return;
    }

    boolean updated = EventController.updateEvent(
        id,
        jTextField3.getText(),
        jTextField4.getText(),
        jFormattedTextField1.getText(),
        jFormattedTextField2.getText()
    );

    if (updated) {
        loadEvents();
        clearFields();
        JOptionPane.showMessageDialog(this, "Event updated successfully");
    } else {
        JOptionPane.showMessageDialog(this, "Event not found");
    }



    }//GEN-LAST:event_jButton9ActionPerformed

    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
  

    String keyword = jTextField1.getText().trim();

    if (keyword.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter title, location, or year");
        return;
    }

    ArrayList<Event> results =
            EventController.linearSearchMultiField(keyword);

    if (results.isEmpty()) {
        JOptionPane.showMessageDialog(this, "No matching events found");
        return;
    }

    DefaultTableModel model =
            (DefaultTableModel) jTable1.getModel();

    model.setRowCount(0); // clear table

    for (Event e : results) {
        model.addRow(new Object[]{
            e.getId(),
            e.getName(),
            e.getLocation(),
            e.getDate(),
            e.getDeadline()
        });
    }



                                
    }//GEN-LAST:event_jButton5ActionPerformed

