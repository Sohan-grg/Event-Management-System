    private void loadEvents() {
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);

    for (Event e : EventData.eventList) {
        model.addRow(new Object[]{
            e.getId(),
            e.getName(),
            e.getLocation(),
            e.getDate(),
            e.getDeadline()
        });
    }
}
